// Dev-time-only generator (run manually with `node scripts/generate-world-map.mjs`
// from frontend/, needs the d3-geo / topojson-client / world-atlas /
// i18n-iso-countries devDependencies): pre-computes a lightweight flat
// world map (SVG path data + per-country marker centroids) from
// world-atlas's public-domain 110m topology, so the Home screen's map
// widget ships as plain static data (src/constants/worldMap.js) with zero
// runtime mapping dependencies. Re-run only if that output needs to change
// (e.g. a different map resolution/projection).
import { geoNaturalEarth1, geoPath, geoCentroid } from "d3-geo";
import { feature } from "topojson-client";
import countriesData from "../node_modules/world-atlas/countries-110m.json" with { type: "json" };
import iso from "i18n-iso-countries";
import fs from "fs";

const WIDTH = 960;
const HEIGHT = 500;

const geo = feature(countriesData, countriesData.objects.countries);

const projection = geoNaturalEarth1().fitSize([WIDTH, HEIGHT], geo);
const pathGen = geoPath(projection);

const paths = [];
const centroids = {};
let skipped = [];

for (const f of geo.features) {
  const alpha2 = iso.numericToAlpha2(f.id);
  const d = pathGen(f);
  if (!d) continue;
  paths.push({ code: alpha2 || null, name: f.properties.name, d });

  if (alpha2) {
    const projected = projection(geoCentroid(f));
    if (projected && Number.isFinite(projected[0]) && Number.isFinite(projected[1])) {
      centroids[alpha2] = [Math.round(projected[0] * 100) / 100, Math.round(projected[1] * 100) / 100];
    }
  } else {
    skipped.push(f.properties.name);
  }
}

console.log("Total features:", geo.features.length);
console.log("Centroids resolved:", Object.keys(centroids).length);
console.log("Skipped (no alpha2 match):", skipped);

const out = `// AUTO-GENERATED by gen_world_map.mjs from world-atlas's countries-110m.json
// (public domain / ISC, Natural Earth data). Do not hand-edit; re-run the
// generator script if it needs to change.
export const WORLD_MAP_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

export const WORLD_MAP_PATHS = ${JSON.stringify(paths)};

// alpha-2 country code -> [x, y] pixel position in the viewBox above
export const WORLD_MAP_CENTROIDS = ${JSON.stringify(centroids)};
`;

fs.writeFileSync(new URL("../src/constants/worldMap.js", import.meta.url), out);
console.log("Wrote src/constants/worldMap.js (" + (out.length / 1024).toFixed(1) + " KB)");
